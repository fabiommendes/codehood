"""Configuração da janela do jogo."""


def window_width() -> int:
    """Devolve a largura da janela, em pixels."""
    return 160


def window_height() -> int:
    """Devolve a altura da janela, em pixels."""
    return 120


def window_title() -> str:
    """Devolve o título da janela."""
    return "Minha primeira janela"


def window_fps() -> int:
    """Devolve quantos quadros por segundo o jogo roda."""
    return 30
